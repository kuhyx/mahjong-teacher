import type { Scene } from './scenes.ts'

// DOCS-tutorial.md from the same scenes the game plays: per scene its step
// images (made by `node scripts/e2e_tutorial.ts --touch --shots docs/tutorial`)
// and a glossary line for each Japanese term. Repo-only text.

/** English meaning of every term a scene glosses (the chip shows jp + romaji only). */
export const MEANING: Record<string, string> = {
  萬子: 'characters suit, 1-9 man',
  筒子: 'dots suit, 1-9 pin',
  索子: 'bamboo suit, 1-9 sou',
  風牌: 'wind tiles: East, South, West, North',
  三元牌: 'dragon tiles: white, green, red',
  役牌: 'value tiles; a triplet of a dragon (or your seat or round wind) is a yaku',
  飜: 'han, the unit of hand value; each yakuhai triplet is 1 han',
  ドラ表示牌: 'dora indicator, the face-up tile on the dead wall',
  ドラ: 'dora, the tile after the indicator in order; each copy in a winning hand adds 1 han (not a yaku)',
  東: 'East; the East seat is the dealer',
  自風: 'seat wind; East, South, West, North go counter-clockwise from the dealer',
  親: 'dealer; wins pay 1.5x and the dealer keeps the seat on a win or tenpai draw',
  点棒: 'point sticks; everyone starts with 25000',
  東一局: 'East round, hand 1 (the round marker in the centre)',
  東風戦: 'East-only match, four or more hands',
  半荘: 'full match, East round then South round',
}

export function tutorialMarkdown(scenes: Scene[], imgDir: string): string {
  const out: string[] = [
    '# Tutorial',
    '',
    'The 🎓 tutorial in the game, step by step. Each scene answers things marked as unclear in the play-through logs',
    '(`pnpm tutorial-coverage` lists which). Generated by `pnpm tutorial-doc`; do not edit by hand.',
    '',
  ]
  for (const s of scenes) {
    out.push(`## ${s.id}`, '', s.doc, '')
    s.steps.forEach((_, i) => out.push(`![${s.id} step ${String(i + 1)}](${imgDir}/${s.id}-${String(i + 1)}.jpg)`))
    out.push('')
    const terms = s.steps.flatMap((st) => (st.gloss ? [st.gloss] : []))
    if (terms.length > 0) {
      out.push('Glossary:', '')
      for (const g of terms) out.push(`- **${g.jp}** (${g.romaji}): ${MEANING[g.jp] ?? 'MISSING MEANING'}`)
      out.push('')
    }
  }
  return out.join('\n')
}
